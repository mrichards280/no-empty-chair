// Builds netlify/lib/voiceovers.mjs for the Script button on /admin/social.
//
//   npm run social:voiceovers -- "path/to/voiceover-scripts.txt" "path/to/reel-project-folder"
//
// voiceover-scripts.txt: blocks like
//   ==== R01 · RATE MY PAGE ====
//   [Hook] Line to read.
// reel-project-folder: the unzipped handoff folder with "Reel R01.dc.html" files;
// each has window.OM_SCENES with every scene's name and length in seconds.
// Scenes with no timing get a length from their word count.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [txtPath, folder] = process.argv.slice(2);
if (!txtPath) {
  console.error('Usage: npm run social:voiceovers -- "voiceover-scripts.txt" ["reel folder"]');
  process.exit(1);
}

const reels = {};
let current = null;
for (const raw of fs.readFileSync(txtPath, "utf8").split(/\r?\n/)) {
  const line = raw.trim();
  const head = line.match(/^=+\s*([RA]\d+)\s*·\s*(.+?)\s*=+$/i);
  if (head) {
    current = head[1].toLowerCase();
    reels[current] = { title: head[2].trim(), scenes: [] };
    continue;
  }
  const scene = line.match(/^\[([^\]]+)\]\s*(.+)$/);
  if (current && scene) reels[current].scenes.push({ name: scene[1], text: scene[2] });
}

const timings = {};
if (folder && fs.existsSync(folder)) {
  for (const file of fs.readdirSync(folder)) {
    const m = file.match(/^(?:Reel|Ad) ([RA]\d+)\.dc\.html$/i);
    if (!m) continue;
    const html = fs.readFileSync(path.join(folder, file), "utf8");
    const raw = html.match(/window\.OM_SCENES\s*=\s*'(.+?)';/)?.[1];
    if (!raw) continue;
    try {
      timings[m[1].toLowerCase()] = Object.fromEntries(JSON.parse(raw).map((s) => [s.name.toLowerCase(), Number(s.dur)]));
    } catch { /* skip unreadable */ }
  }
}

// about 2.6 spoken words per second, never under 2 seconds
const byWords = (text) => Math.max(2, Math.round((text.split(/\s+/).length / 2.6) * 2) / 2);

for (const [id, reel] of Object.entries(reels)) {
  let t = 0;
  for (const s of reel.scenes) {
    const dur = timings[id]?.[s.name.toLowerCase()] || byWords(s.text);
    s.start = Math.round(t * 100) / 100;
    s.dur = dur;
    t += dur;
  }
  reel.timed = Boolean(timings[id]);
  reel.length = Math.round(t * 10) / 10;
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "netlify", "lib", "voiceovers.mjs");
fs.writeFileSync(out, `// Generated by scripts/social-voiceovers.mjs. Reel voiceover lines with scene timings.\nexport default ${JSON.stringify(reels, null, 2)};\n`);
console.log(`Wrote ${Object.keys(reels).length} reels to ${path.relative(process.cwd(), out)}`);
for (const [id, r] of Object.entries(reels)) console.log(`  ${id}  ${r.scenes.length} lines  ${r.length}s  ${r.timed ? "scene timings" : "estimated timings"}`);
